namespace SupermarketSystem.Application.Common.Interfaces;

/// <summary>
/// فحص الصلاحيات *حيًّا* بكل طلب — بخلاف صلاحية "تجاوز الفروع" المحفوظة
/// بالتوكن (راجع RealCurrentUserContext)، صلاحيات العمليات العادية (بيع،
/// إرجاع، اعتماد جرد، إلخ) لازم تُفحص من قاعدة البيانات كل مرة، لا من
/// التوكن — سحب صلاحية "إلغاء بيع" من كاشير لازم يصير فعّالًا فورًا، لا
/// يستنى انتهاء توكنه.
///
/// هذا الفرق (بعض الصلاحيات بالتوكن، والبقية حية) ليس تناقضًا — الأولى
/// (تجاوز الفروع) قيد بنيوي على *أي بيانات المستخدم أصلًا قادر يشوفها*
/// (لازم يكون معروفًا وقت بناء المرشِّح، قبل أي استعلام)، والثانية *ماذا
/// يقدر يفعل بالبيانات اللي يشوفها* — قرار يُفحص وقت التنفيذ، طبيعي يكون
/// حيًّا.
/// </summary>
public interface IPermissionChecker
{
    Task<bool> HasPermissionAsync(Guid userId, string permissionCode, CancellationToken cancellationToken);
}
